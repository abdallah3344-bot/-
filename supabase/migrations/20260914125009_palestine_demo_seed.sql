-- ============================================================
-- توطين البيانات التجريبية للسياق الفلسطيني
-- ------------------------------------------------------------
-- كانت سعودية: الرياض، هوية بعشر خانات، جوال يبدأ بـ 05، ومحكمة
-- تجارية في الرياض. نُعدّل نصوص الدالة القائمة بدل إعادة كتابتها
-- كاملة، فالتغيير كله في قيم حرفية معدودة.
-- ============================================================

do $migrate$
declare
  _src text;
begin
  select pg_get_functiondef(p.oid) into _src
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.proname = 'seed_demo_data';

  if _src is null then
    raise exception 'الدالة seed_demo_data غير موجودة';
  end if;

  -- أسماء الموكلين
  _src := replace(_src,
    '''شركة الأفق للتجارة'', ''مؤسسة البيان للمقاولات'', ''أحمد سالم الحربي'',',
    '''شركة الأمل للتجارة العامة'', ''مؤسسة النهضة للمقاولات'', ''محمد خالد عبد الله'',');
  _src := replace(_src,
    '''شركة النخبة للاستثمار'', ''فاطمة عبدالله الزهراني''',
    '''شركة القدس للاستثمار'', ''سميرة يوسف حمدان''');

  -- عناوين القضايا
  _src := replace(_src, '''مطالبة مالية ضد شركة الوفاق''', '''مطالبة مالية ضد شركة الوفاء''');
  _src := replace(_src, '''نزاع عقد مقاولة — مشروع الرياض''', '''نزاع عقد مقاولة — مشروع رام الله''');
  _src := replace(_src, '''قضية أحوال شخصية — حضانة''', '''أحوال شخصية شرعية — حضانة''');

  -- المحكمة الافتراضية
  _src := replace(_src,
    '''المحكمة التجارية'', ''تجارية'', ''الرياض''',
    '''محكمة بداية رام الله'', ''first_instance'', ''رام الله والبيرة''');

  -- رقم الهوية الفلسطيني تسع خانات، والجوال يبدأ بـ 059
  _src := replace(_src,
    '''10'' || lpad((_i * 7919 % 100000000)::text, 8, ''0''),',
    'lpad((_i * 7919 % 1000000000)::text, 9, ''0''),');
  _src := replace(_src,
    '''05'' || lpad((_i * 1237 % 100000000)::text, 8, ''0''),',
    '''059'' || lpad((_i * 1237 % 10000000)::text, 7, ''0''),');

  -- العنوان والمحافظة
  _src := replace(_src, '''الرياض — حي العليا''', '''رام الله — الماصيون''');
  _src := replace(_src, '''الرياض'', current_date - (_i * 21)', '''رام الله والبيرة'', current_date - (_i * 21)');

  if _src like '%الرياض%' then
    raise exception 'بقيت إشارة إلى الرياض في دالة البيانات التجريبية';
  end if;

  execute _src;
end
$migrate$;;
